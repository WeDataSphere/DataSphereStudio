package com.webank.wedatasphere.dss.datamap.datamap;

public class DMSDatasetSubsystem {
    private String subsystemId;
    private String subsystemName;
    private String datasetId;
    private String busiResDept;

    public String getSubsystemId() {
        return subsystemId;
    }

    public void setSubsystemId(String subsystemId) {
        this.subsystemId = subsystemId;
    }

    public String getSubsystemName() {
        return subsystemName;
    }

    public void setSubsystemName(String subsystemName) {
        this.subsystemName = subsystemName;
    }

    public String getDatasetId() {
        return datasetId;
    }

    public void setDatasetId(String datasetId) {
        this.datasetId = datasetId;
    }

    public String getBusiResDept() {
        return busiResDept;
    }

    public void setBusiResDept(String busiResDept) {
        this.busiResDept = busiResDept;
    }
}
